import { existsSync, readdirSync, readFileSync, writeFileSync } from "fs";
import path from "path";

/**
 * Turns evals/results/search-<size>.json into:
 *  - evals/recall-latency.svg: recall@10 x p50 latency, one panel per table
 *    size, free-text queries on top and log queries below;
 *  - the tables between the markers in SEMANTIC_SEARCH.md (the prose around
 *    them is written by hand and left untouched). A search-<size>-ef.json
 *    (an extra ef_search sweep, `pnpm eval:search --ef=... --out=...`) adds
 *    a table of its own.
 *
 * Usage: pnpm eval:report
 */

const ROOT = path.resolve(__dirname, "../..");
const RESULTS_DIR = path.join(ROOT, "evals/results");
const SVG_PATH = path.join(ROOT, "evals/recall-latency.svg");
const DOC_PATH = path.join(ROOT, "SEMANTIC_SEARCH.md");
const START = "<!-- results:start (generated by pnpm eval:report, do not edit) -->";
const END = "<!-- results:end -->";

interface Method {
   method: string;
   recall_at_k: number | null;
   recall_range?: [number, number];
   precision_at_k: number;
   latency_ms: { p50: number; p95: number };
   empty_results: number;
   per_query: { precision: number; kind?: string }[];
}
interface Build {
   m: number;
   ef_construction: number;
   build_ms: number;
   maintenance_work_mem_mb: number;
   size_bytes: { hnsw: number; gin: number; table_heap: number };
}
interface Result {
   rows: number;
   k: number;
   rounds: number;
   repeats: number;
   hnsw_builds: Build[];
   embed_query_ms: { p50: number };
   log_queries: Method[];
   text_queries: Method[];
}

const results: Result[] = readdirSync(RESULTS_DIR)
   .filter((f) => /^search-\d+[km]\.json$/.test(f))
   .map((f) => JSON.parse(readFileSync(path.join(RESULTS_DIR, f), "utf8")) as Result)
   .sort((a, b) => a.rows - b.rows);
if (results.length === 0) throw new Error("no evals/results/search-*.json; run pnpm eval:search first");

const scale = (rows: number) => (rows >= 1_000_000 ? `${rows / 1_000_000}M` : `${rows / 1000}k`);
const pct = (n: number | null | undefined) => (n == null ? "–" : `${(n * 100).toFixed(1)}%`);
const msFmt = (n: number) => (n < 10 ? n.toFixed(2) : n < 100 ? n.toFixed(1) : Math.round(n).toLocaleString("en-US"));
const mbFmt = (b: number) => `${(b / 1024 / 1024).toFixed(b < 100 * 1024 * 1024 ? 1 : 0)} MB`;
const secFmt = (ms: number) => (ms < 60_000 ? `${(ms / 1000).toFixed(1)} s` : `${(ms / 60_000).toFixed(1)} min`);

// HNSW configs present in every result, in run order.
const configs = [...new Set(results.flatMap((r) => r.hnsw_builds.map((b) => `m=${b.m} efc=${b.ef_construction}`)))];
const EF = [10, 20, 40, 80, 160];
const hnswName = (cfg: string, ef: number) => `HNSW ${cfg} ef_search=${ef}`;
const find = (ms: Method[], name: string) => ms.find((m) => m.method === name);
// Hybrid runs on every config up to 100k and only on the last one at 1M
// (--hybrid-last-only); the last config is the one the tables compare.
const findPrefix = (ms: Method[], prefix: string) => [...ms].reverse().find((m) => m.method.startsWith(prefix));

// ---------------------------------------------------------------- chart ----

// Reference palette (dataviz skill), first three categorical slots: they
// validate all-pairs in both modes, as small multiples require. Aqua is under
// 3:1 on the light surface, so every series is also direct-labelled, has its
// own marker shape, and the tables below repeat every value.
const SERIES = [
   { light: "#2a78d6", dark: "#3987e5", shape: "circle" },
   { light: "#eb6834", dark: "#d95926", shape: "square" },
   { light: "#1baf7a", dark: "#199e70", shape: "triangle" },
];

function chart(): string {
   const panelW = 280;
   const panelH = 190;
   const left = 64;
   const gapX = 40;
   const top = 110;
   const W = Math.max(980, left + results.length * panelW + (results.length - 1) * gapX + 80);
   const gapY = 100;
   const rowsSpec = [
      { key: "text_queries" as const, label: "Free-text queries (60 typed searches)" },
      { key: "log_queries" as const, label: "Log queries (100 logs from the table)" },
   ];
   const H = top + rowsSpec.length * (panelH + gapY) - 40;

   const plotted = (ms: Method[]) => ms.filter((m) => m.recall_at_k !== null && /^(HNSW|vector exact)/.test(m.method));
   const lat = results.flatMap((r) => rowsSpec.flatMap((row) => plotted(r[row.key]).map((m) => m.latency_ms.p50)));
   // Shared log x axis (latency is comparable across rows and sizes), with
   // both ends on a labelled tick.
   const TICKS = [0.1, 0.3, 1, 3, 10, 30, 100, 300, 1000, 3000, 10000, 30000];
   const xMin = [...TICKS].reverse().find((t) => t <= Math.min(...lat) * 0.95) ?? 0.1;
   const xMax = TICKS.find((t) => t >= Math.max(...lat) * 1.6) ?? 30000;
   const x = (v: number) => (Math.log10(v) - Math.log10(xMin)) / (Math.log10(xMax) - Math.log10(xMin)) * panelW;
   const xTicks = TICKS.filter((t) => t >= xMin && t <= xMax);
   // One y scale per row: the same across table sizes, so a row reads as
   // "what happens as the table grows".
   const yScale = rowsSpec.map((row) => {
      const lo = Math.min(...results.flatMap((r) => plotted(r[row.key]).map((m) => m.recall_at_k!)));
      const yMin = Math.max(0, Math.floor((lo * 100 - 2) / 10) * 10);
      const ticks: number[] = [];
      for (let t = yMin; t <= 100; t += yMin >= 80 ? 5 : 10) ticks.push(t);
      return { y: (v: number) => panelH - ((v * 100 - yMin) / (100 - yMin)) * panelH, ticks };
   });

   const marker = (shape: string, cx: number, cy: number, cls: string, title: string) => {
      const t = `<title>${title}</title>`;
      if (shape === "square") return `<rect class="${cls} ring" x="${(cx - 4).toFixed(1)}" y="${(cy - 4).toFixed(1)}" width="8" height="8" rx="1.5">${t}</rect>`;
      if (shape === "triangle") {
         const p = [[cx, cy - 5.2], [cx - 5, cy + 3.8], [cx + 5, cy + 3.8]].map(([a, b]) => `${a.toFixed(1)},${b.toFixed(1)}`).join(" ");
         return `<polygon class="${cls} ring" points="${p}">${t}</polygon>`;
      }
      return `<circle class="${cls} ring" cx="${cx.toFixed(1)}" cy="${cy.toFixed(1)}" r="4">${t}</circle>`;
   };

   const out: string[] = [];
   out.push(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}" font-family="system-ui, -apple-system, 'Segoe UI', sans-serif" role="img" aria-labelledby="t d">`);
   out.push(`<title id="t">HNSW recall@10 vs p50 latency</title>`);
   out.push(`<desc id="d">recall@10 against exact search versus median query latency, per HNSW build config and ef_search, for each table size; free-text queries on top, log queries below. Exact search is the gray reference point.</desc>`);
   // Plain colors per class (no CSS variables: librsvg-based viewers ignore
   // them), declared once for light and again for dark mode.
   const css = (t: { surface: string; ink: string; ink2: string; muted: string; grid: string; axis: string }, mode: "light" | "dark") => `
  .bg { fill: ${t.surface}; }
  .grid { stroke: ${t.grid}; stroke-width: 1; }
  .axis { stroke: ${t.axis}; stroke-width: 1; }
  .tick { fill: ${t.muted}; font-size: 11px; font-variant-numeric: tabular-nums; }
  .h1 { fill: ${t.ink}; font-size: 15px; font-weight: 600; }
  .h2 { fill: ${t.ink}; font-size: 13px; font-weight: 600; }
  .lab { fill: ${t.ink2}; font-size: 11px; }
  .ring { stroke: ${t.surface}; stroke-width: 2; }
  .ref { fill: ${t.muted}; }
  ${SERIES.map((sr, i) => `.l${i + 1} { stroke: ${sr[mode]}; stroke-width: 2; fill: none; stroke-linejoin: round; stroke-linecap: round; } .f${i + 1} { fill: ${sr[mode]}; }`).join("\n  ")}`;
   const LIGHT = { surface: "#fcfcfb", ink: "#0b0b0b", ink2: "#52514e", muted: "#898781", grid: "#e1e0d9", axis: "#c3c2b7" };
   const DARK = { surface: "#1a1a19", ink: "#f0efec", ink2: "#c3c2b7", muted: "#898781", grid: "#2c2c2a", axis: "#383835" };
   out.push(`<style>${css(LIGHT, "light")}\n  @media (prefers-color-scheme: dark) {${css(DARK, "dark")}\n  }\n</style>`);
   out.push(`<rect class="bg" width="${W}" height="${H}"/>`);
   out.push(`<text class="h1" x="${left}" y="24">HNSW recall@10 vs p50 latency (each point is one ef_search: 10, 20, 40, 80, 160)</text>`);

   // legend (text width estimated at ~6.3px per character of 11px sans)
   let lx = left;
   configs.forEach((cfg, i) => {
      const label = `HNSW ${cfg}${cfg === "m=16 efc=64" ? " (pgvector default)" : ""}`;
      out.push(`<line class="l${i + 1}" x1="${lx}" y1="50" x2="${lx + 22}" y2="50"/>`);
      out.push(marker(SERIES[i].shape, lx + 11, 50, `f${i + 1}`, cfg));
      out.push(`<text class="lab" x="${lx + 30}" y="54">${label}</text>`);
      lx += 30 + label.length * 6.3 + 24;
   });
   out.push(`<circle class="ref ring" cx="${lx + 6}" cy="50" r="4"/><text class="lab" x="${lx + 16}" y="54">exact search (seq scan)</text>`);

   rowsSpec.forEach((row, ri) => {
      const oy = top + ri * (panelH + gapY);
      const { y, ticks: yTicks } = yScale[ri];
      out.push(`<text class="h2" x="${left}" y="${oy - 34}">${row.label}</text>`);
      results.forEach((r, ci) => {
         const ox = left + ci * (panelW + gapX);
         out.push(`<g transform="translate(${ox},${oy})">`);
         for (const t of yTicks) {
            out.push(`<line class="grid" x1="0" x2="${panelW}" y1="${y(t / 100).toFixed(1)}" y2="${y(t / 100).toFixed(1)}"/>`);
            if (ci === 0) out.push(`<text class="tick" x="-8" y="${(y(t / 100) + 4).toFixed(1)}" text-anchor="end">${t}%</text>`);
         }
         out.push(`<line class="axis" x1="0" x2="${panelW}" y1="${panelH}" y2="${panelH}"/>`);
         for (const t of xTicks) {
            out.push(`<line class="axis" x1="${x(t).toFixed(1)}" x2="${x(t).toFixed(1)}" y1="${panelH}" y2="${panelH + 4}"/>`);
            out.push(`<text class="tick" x="${x(t).toFixed(1)}" y="${panelH + 17}" text-anchor="middle">${t >= 1000 ? `${t / 1000}s` : t}</text>`);
         }
         out.push(`<text class="lab" x="${panelW}" y="${panelH + 34}" text-anchor="end">p50 latency, ms (log scale)</text>`);
         out.push(`<text class="lab" x="0" y="-10" font-weight="600">${scale(r.rows)} rows</text>`);

         const ends: { y: number; text: string; i: number; x: number }[] = [];
         configs.forEach((cfg, i) => {
            const pts = EF.map((ef) => find(r[row.key], hnswName(cfg, ef))).filter((m): m is Method => !!m);
            if (pts.length === 0) return;
            const d = pts.map((m, j) => `${j ? "L" : "M"}${x(m.latency_ms.p50).toFixed(1)},${y(m.recall_at_k!).toFixed(1)}`).join(" ");
            out.push(`<path class="l${i + 1}" d="${d}"/>`);
            pts.forEach((m, j) =>
               out.push(marker(SERIES[i].shape, x(m.latency_ms.p50), y(m.recall_at_k!), `f${i + 1}`,
                  `${scale(r.rows)} · ${cfg} · ef_search=${EF[j]}: recall ${pct(m.recall_at_k)}, p50 ${msFmt(m.latency_ms.p50)} ms`)),
            );
            const last = pts[pts.length - 1];
            ends.push({ y: y(last.recall_at_k!), text: pct(last.recall_at_k), i, x: x(last.latency_ms.p50) });
         });
         // Direct label at each line's last point (ef_search=160), nudged apart.
         ends.sort((a, b) => a.y - b.y);
         for (let j = 1; j < ends.length; j++) ends[j].y = Math.max(ends[j].y, ends[j - 1].y + 12);
         const lastX = Math.max(...configs.map((cfg) => {
            const m = find(r[row.key], hnswName(cfg, 160));
            return m ? x(m.latency_ms.p50) : 0;
         }));
         // Each end label carries its series' marker, so the number is never
         // identified by position or color alone.
         for (const e of ends) {
            out.push(marker(SERIES[e.i].shape, lastX + 14, e.y, `f${e.i + 1}`, configs[e.i]));
            out.push(`<text class="lab" x="${(lastX + 22).toFixed(1)}" y="${(e.y + 4).toFixed(1)}">${e.text}</text>`);
         }

         const ex = find(r[row.key], "vector exact (seq)");
         if (ex) {
            out.push(`<circle class="ref ring" cx="${x(ex.latency_ms.p50).toFixed(1)}" cy="${y(1).toFixed(1)}" r="4"><title>${scale(r.rows)} · exact: recall 100%, p50 ${msFmt(ex.latency_ms.p50)} ms</title></circle>`);
            // Above the point, in the strip between the panel title and the
            // 100% gridline, where no line or end label can be.
            out.push(`<text class="lab" x="${Math.max(120, x(ex.latency_ms.p50)).toFixed(1)}" y="${(y(1) - 10).toFixed(1)}" text-anchor="middle">exact, ${msFmt(ex.latency_ms.p50)} ms</text>`);
         }
         out.push(`</g>`);
      });
   });
   out.push(`</svg>`);
   return out.join("\n") + "\n";
}

// --------------------------------------------------------------- tables ----

function table(head: string[], rows: string[][], align: ("l" | "r")[]): string {
   const sep = align.map((a) => (a === "r" ? "---:" : ":---"));
   return [head, sep, ...rows].map((r) => `| ${r.join(" | ")} |`).join("\n");
}

function methodRows(r: Result, key: "text_queries" | "log_queries"): string[][] {
   const ms = r[key];
   const picks: { label: string; m?: Method }[] = [
      { label: "LIKE `%…%` (no index)", m: find(ms, "LIKE (no index)") },
      { label: "full-text (GIN)", m: find(ms, "full-text (GIN)") },
      { label: "vector, exact (seq scan)", m: find(ms, "vector exact (seq)") },
      ...configs.flatMap((cfg) =>
         [40, 160].map((ef) => ({ label: `HNSW ${cfg}, ef_search=${ef}`, m: find(ms, hnswName(cfg, ef)) })),
      ),
      { label: "hybrid RRF (full-text + HNSW)", m: findPrefix(ms, "hybrid RRF") },
   ];
   return picks
      .filter((p) => p.m)
      .map(({ label, m }) => [
         label,
         m!.recall_range ? `${pct(m!.recall_at_k)} (${(m!.recall_range[0] * 100).toFixed(0)}–${(m!.recall_range[1] * 100).toFixed(0)})` : pct(m!.recall_at_k),
         pct(m!.precision_at_k),
         msFmt(m!.latency_ms.p50),
         msFmt(m!.latency_ms.p95),
      ]);
}

function report(): string {
   const parts: string[] = [START, ""];
   parts.push(
      `Measured with PostgreSQL 17 + pgvector, warm cache, client-side wall time over a local socket; the runs are not confirmed to come from the same machine. ` +
         `Recall is tie-aware recall@10 against exact search; precision@10 is the share of the 10 results with the expected root cause. ` +
         `Where builds were repeated, recall shows the mean and the (min–max) across builds.`,
      "",
   );
   parts.push("### HNSW build cost", "");
   parts.push(
      table(
         ["rows", "table heap", "GIN", ...configs.map((c) => `HNSW ${c}`)],
         results.map((r) => {
            const per = configs.map((cfg) => {
               const bs = r.hnsw_builds.filter((b) => `m=${b.m} efc=${b.ef_construction}` === cfg);
               if (!bs.length) return "–";
               const avg = bs.reduce((a, b) => a + b.build_ms, 0) / bs.length;
               return `${secFmt(avg)}, ${mbFmt(bs[0].size_bytes.hnsw)}`;
            });
            const b = r.hnsw_builds[0];
            return [scale(r.rows), mbFmt(b.size_bytes.table_heap), mbFmt(b.size_bytes.gin), ...per];
         }),
         ["l", "r", "r", ...configs.map(() => "r" as const)],
      ),
      "",
   );
   for (const [key, title] of [
      ["text_queries", "Free-text queries (60 typed searches, `evals/text_queries.json`)"],
      ["log_queries", "Log queries (100 logs sampled from the table, `evals/ground_truth*.json`)"],
   ] as const) {
      parts.push(`### ${title}`, "");
      for (const r of results) {
         parts.push(`**${scale(r.rows)} rows** (${r.repeats} build${r.repeats > 1 ? "s" : ""} per config, ${r.rounds} measured round${r.rounds > 1 ? "s" : ""})`, "");
         parts.push(table(["method", "recall@10", "precision@10", "p50 ms", "p95 ms"], methodRows(r, key), ["l", "r", "r", "r", "r"]), "");
      }
   }
   parts.push("### Free-text precision@10 by kind of query", "");
   const lastCfg = configs[configs.length - 1];
   parts.push(
      table(
         ["rows", "kind", "LIKE", "full-text", "vector exact", `HNSW ${lastCfg} ef=40`, "hybrid"],
         results.flatMap((r) =>
            ["keyword", "mixed", "paraphrase"].map((kind) => {
               const p = (m?: Method) => {
                  if (!m) return "–";
                  const qs = m.per_query.filter((q) => q.kind === kind);
                  return pct(qs.reduce((a, q) => a + q.precision, 0) / qs.length);
               };
               const ms = r.text_queries;
               return [scale(r.rows), kind, p(find(ms, "LIKE (no index)")), p(find(ms, "full-text (GIN)")), p(find(ms, "vector exact (seq)")), p(find(ms, hnswName(lastCfg, 40))), p(findPrefix(ms, "hybrid RRF"))];
            }),
         ),
         ["l", "l", "r", "r", "r", "r", "r"],
      ),
      "",
   );
   parts.push("### Free-text queries where a method returns nothing relevant (precision@10 = 0, of 60)", "");
   const zeroCols: [string, (ms: Method[]) => Method | undefined][] = [
      ["LIKE", (ms) => find(ms, "LIKE (no index)")],
      ["full-text", (ms) => find(ms, "full-text (GIN)")],
      ["vector exact", (ms) => find(ms, "vector exact (seq)")],
      [`HNSW ${lastCfg} ef=40`, (ms) => find(ms, hnswName(lastCfg, 40))],
      [`HNSW ${lastCfg} ef=160`, (ms) => find(ms, hnswName(lastCfg, 160))],
      ["hybrid", (ms) => findPrefix(ms, "hybrid RRF")],
   ];
   parts.push(
      table(
         ["rows", ...zeroCols.map(([h]) => h)],
         results.map((r) => [
            scale(r.rows),
            ...zeroCols.map(([, pick]) => {
               const m = pick(r.text_queries);
               return m ? String(m.per_query.filter((q) => q.precision === 0).length) : "–";
            }),
         ]),
         ["l", ...zeroCols.map(() => "r" as const)],
      ),
      "",
   );
   for (const f of readdirSync(RESULTS_DIR).filter((f) => /^search-\d+[km]-ef\.json$/.test(f)).sort()) {
      const r = JSON.parse(readFileSync(path.join(RESULTS_DIR, f), "utf8")) as Result;
      const cfg = `m=${r.hnsw_builds[0].m} efc=${r.hnsw_builds[0].ef_construction}`;
      parts.push(`### Larger ef_search, ${scale(r.rows)} rows, HNSW ${cfg} (\`evals/results/${f}\`, a separate build)`, "");
      const rows = r.text_queries
         .filter((m) => m.method.startsWith(`HNSW ${cfg} ef_search=`))
         .map((m) => {
            const lm = find(r.log_queries, m.method)!;
            return [m.method.split("=").pop()!, pct(m.recall_at_k), pct(m.precision_at_k), msFmt(m.latency_ms.p50), msFmt(m.latency_ms.p95), pct(lm.recall_at_k)];
         });
      parts.push(table(["ef_search", "free-text recall@10", "free-text precision@10", "p50 ms", "p95 ms", "log-query recall@10"], rows, ["r", "r", "r", "r", "r", "r"]), "");
   }
   parts.push(`Embedding a typed query with the local model adds ~${msFmt(results[0].embed_query_ms.p50)} ms (p50) before any vector search.`, "");
   parts.push(END);
   return parts.join("\n");
}

writeFileSync(SVG_PATH, chart());
console.log(`wrote ${path.relative(ROOT, SVG_PATH)} (${results.map((r) => scale(r.rows)).join(", ")})`);

if (existsSync(DOC_PATH)) {
   const doc = readFileSync(DOC_PATH, "utf8");
   const a = doc.indexOf(START);
   const b = doc.indexOf(END);
   if (a < 0 || b < 0) throw new Error(`${path.basename(DOC_PATH)} has no results markers`);
   writeFileSync(DOC_PATH, doc.slice(0, a) + report() + doc.slice(b + END.length));
   console.log(`updated tables in ${path.basename(DOC_PATH)}`);
} else {
   console.log(`${path.basename(DOC_PATH)} not found; tables:\n\n${report()}`);
}
