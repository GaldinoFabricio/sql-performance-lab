import { mkdirSync, readFileSync, writeFileSync } from "fs";
import path from "path";
import db from "../db/knex";
import { embed, toPgVector } from "../embeddings/embedder";
import { DEFAULT_SEED, generateLogs } from "../logs/generator";
import { mean, percentile } from "../evals/metrics";
import { routeWeights } from "../search/routing";
import { fullTextSearch, Hit, hybridSearch, vectorSearch } from "../search/search";
import { codesIn, knownCodes as loadKnownCodes } from "../search/codes";
import { templateSearch, templatesCurrent } from "../search/templates";
import { SEARCH_DEFAULTS } from "../services/search.service";

/**
 * How each search mode handles a typed error code (ECONNRESET, x509, 40P01).
 *
 * evals/text_queries.json has only 8 queries with a code, too few to measure
 * a fix for codes. This eval builds one query set from the data instead:
 *
 *   pnpm eval:codes --generate   writes evals/code_queries.json, no database:
 *      every error_code the log generator emits, in 3 forms
 *        exact     "ECONNRESET"
 *        lower     "econnreset"     (people don't type codes in capitals)
 *        sentence  "lots of ECONNRESET errors since the deploy"
 *      Relevant = a log whose root_cause is one of the code's root causes.
 *      Some codes belong to several (ECONNREFUSED: cache and database), so a
 *      query can have more than one; that is what the code means.
 *
 *   pnpm eval:codes              runs the queries the way GET /search/logs
 *      does by default (no INFO, ef_search 160, hybrid with 40 candidates):
 *      vector, hybrid (fixed 1/1 and routed), fulltext and template, plus
 *      "error_code lookup", the newest logs whose error_code equals a code
 *      in the query (case-insensitive). The lookup is not a mode of the API;
 *      it shows how far an exact code match alone gets.
 *      "hybrid + codes, cw=N" is hybrid with the third RRF list of logs that
 *      carry a code found in the query (src/search/codes.ts), at weight N.
 *      The same hybrid variants also run on evals/text_queries.json, to check
 *      that queries without a code don't change.
 *
 * Usage: pnpm eval:codes [--generate] [--cw=1,2] [--out=evals/results/codes-10k.json]
 */

interface CodeQuery { text: string; code: string; form: Form; expected: string[]; logs: number }
type Form = (typeof FORMS)[number];
type Method = "vector" | "hybrid" | "hybrid routed" | "fulltext" | "template" | "error_code lookup" | `hybrid + codes, cw=${number}`;

const ROOT = path.resolve(__dirname, "../..");
const QUERIES = path.join(ROOT, "evals/code_queries.json");
const K = 10;
const FORMS = ["exact", "lower", "sentence"] as const;
const GENERATE_ROWS = 200_000; // enough for every code to show up many times
const flag = (name: string) => process.argv.find((a) => a.startsWith(`--${name}=`))?.split("=")[1];
const CODE_WEIGHTS = (flag("cw") ?? "1,2").split(",").map(Number);
const pct = (x: number) => `${(x * 100).toFixed(1)}%`;

function generate() {
   const causes = new Map<string, Map<string, number>>();
   for (const log of generateLogs({ count: GENERATE_ROWS, seed: DEFAULT_SEED })) {
      if (!log.error_code || log.level === "INFO") continue;
      const m = causes.get(log.error_code) ?? causes.set(log.error_code, new Map()).get(log.error_code)!;
      m.set(log.root_cause!, (m.get(log.root_cause!) ?? 0) + 1);
   }
   const queries: CodeQuery[] = [];
   for (const [code, m] of [...causes].sort(([a], [b]) => a.localeCompare(b))) {
      const expected = [...m.keys()].sort();
      const logs = [...m.values()].reduce((a, b) => a + b, 0);
      const forms: Record<Form, string> = {
         exact: code,
         lower: code.toLowerCase(),
         sentence: `lots of ${code} errors since the deploy`,
      };
      for (const form of FORMS) queries.push({ text: forms[form], code, form, expected, logs });
   }
   writeFileSync(
      QUERIES,
      JSON.stringify(
         {
            description:
               "Error-code queries generated by `pnpm eval:codes --generate` from the log generator " +
               `(seed ${DEFAULT_SEED}, ${GENERATE_ROWS.toLocaleString("en-US")} logs, INFO excluded). ` +
               "expected = the root causes the code appears in; logs = how many generated logs carry it.",
            codes: causes.size,
            ambiguous: [...causes].filter(([, m]) => m.size > 1).map(([c, m]) => ({ code: c, root_causes: [...m.keys()].sort() })),
            queries,
         },
         null,
         2,
      ) + "\n",
   );
   console.log(`wrote ${path.relative(ROOT, QUERIES)}: ${causes.size} codes x ${FORMS.length} forms = ${queries.length} queries`);
}

async function run() {
   const { queries }: { queries: CodeQuery[] } = JSON.parse(readFileSync(QUERIES, "utf8"));
   const { rows: [info] } = await db.raw("SELECT count(*)::int AS rows, count(embedding)::int AS embedded FROM logs");
   if (info.rows === 0 || info.embedded !== info.rows) throw new Error("run pnpm seed:logs and pnpm embed:logs first");
   const withTemplates = await templatesCurrent(db);
   if (!withTemplates) console.warn("templates are stale or missing (pnpm templates:build): skipping template mode");
   const size = info.rows >= 1_000_000 ? `${info.rows / 1_000_000}m` : `${info.rows / 1000}k`;

   const knownCodes = await loadKnownCodes(db);

   const codeMethods = CODE_WEIGHTS.map((w) => `hybrid + codes, cw=${w}` as Method);
   const methods: Method[] = [
      "vector", "hybrid", "hybrid routed", ...codeMethods, "fulltext",
      ...(withTemplates ? (["template"] as const) : []), "error_code lookup",
   ];
   const per: Record<string, { precision: number; exactCode: number; results: number; ms: number }[]> = {};

   const searchOnce = async (q: { text: string }, vec: string, m: Method): Promise<Hit[]> =>
      db.transaction(async (trx) => {
         await trx.raw(`SET LOCAL hnsw.ef_search = ${SEARCH_DEFAULTS.efSearch}`);
         const hybrid = (w: { vectorWeight: number; keywordWeight: number; codes?: string[]; codeWeight?: number }) =>
            hybridSearch(trx, q.text, vec, K, null, { candidates: SEARCH_DEFAULTS.hybridCandidates, rrfK: SEARCH_DEFAULTS.rrfK, notInfo: true, ...w });
         if (m.startsWith("hybrid + codes")) {
            const codeWeight = Number(m.split("cw=")[1]);
            return hybrid({ vectorWeight: SEARCH_DEFAULTS.vectorWeight, keywordWeight: SEARCH_DEFAULTS.keywordWeight, codes: codesIn(q.text, knownCodes), codeWeight });
         }
         switch (m) {
            case "vector": return vectorSearch(trx, vec, K, null, true);
            case "hybrid": return hybrid({ vectorWeight: SEARCH_DEFAULTS.vectorWeight, keywordWeight: SEARCH_DEFAULTS.keywordWeight });
            case "hybrid routed": return hybrid(routeWeights(q.text));
            case "fulltext": return fullTextSearch(trx, q.text, K, null, true);
            case "template": return templateSearch(trx, vec, K, null, true);
            case "error_code lookup": {
               const codes = codesIn(q.text, knownCodes);
               if (codes.length === 0) return [];
               const { rows } = await trx.raw(
                  "SELECT id, root_cause FROM logs WHERE error_code = ANY(?) ORDER BY id DESC LIMIT ?",
                  [codes, K],
               );
               return rows.map((r: any) => ({ id: Number(r.id), root_cause: r.root_cause }));
            }
         }
      });

   for (const q of queries) {
      const vec = toPgVector((await embed([q.text]))[0]);
      for (const m of methods) {
         await searchOnce(q, vec, m); // warm-up
         const times: number[] = [];
         let hits: Hit[] = [];
         for (let r = 0; r < 3; r++) {
            const t = performance.now();
            hits = await searchOnce(q, vec, m);
            times.push(performance.now() - t);
         }
         const ids = hits.map((h) => h.id);
         const { rows } = await db.raw("SELECT count(*)::int AS n FROM logs WHERE id = ANY(?::bigint[]) AND error_code = ?", [ids, q.code]);
         (per[m] ??= []).push({
            precision: hits.filter((h) => h.root_cause !== null && q.expected.includes(h.root_cause)).length / K,
            exactCode: rows[0].n / K,
            results: hits.length,
            ms: percentile(times, 50),
         });
      }
   }

   // ---- report ----
   const groups = [{ name: "all", idx: queries.map((_, i) => i) }, ...FORMS.map((f) => ({ name: f, idx: queries.flatMap((q, i) => (q.form === f ? [i] : [])) }))];
   const inMessage = await Promise.all(
      [...new Set(queries.map((q) => q.code))].map(async (code) => {
         const { rows } = await db.raw(
            "SELECT count(*) FILTER (WHERE position(lower(?) in lower(message)) > 0)::float / greatest(count(*), 1) AS share FROM logs WHERE error_code = ?",
            [code, code],
         );
         return [code, Number(rows[0].share)] as const;
      }),
   );
   const inMsg = new Map(inMessage);

   const summary = methods.map((m) => {
      const xs = per[m];
      const byForm = Object.fromEntries(groups.slice(1).map((g) => [g.name, mean(g.idx.map((i) => xs[i].precision))]));
      return {
         method: m,
         precision: mean(xs.map((x) => x.precision)),
         by_form: byForm,
         exact_code_share: mean(xs.map((x) => x.exactCode)),
         zero_relevant: Object.fromEntries(groups.map((g) => [g.name, g.idx.filter((i) => xs[i].precision === 0).length])),
         p50_ms: percentile(xs.map((x) => x.ms), 50),
      };
   });

   console.log(`logs: ${info.rows.toLocaleString()} rows; ${queries.length} code queries (${queries.length / FORMS.length} codes x ${FORMS.join("/")}); no INFO, ef_search ${SEARCH_DEFAULTS.efSearch}\n`);
   console.log(`${"method".padEnd(20)}${"precision@10".padEnd(14)}${FORMS.map((f) => f.padEnd(10)).join("")}${"same code".padEnd(11)}${`0 relevant (of ${queries.length / FORMS.length} per form)`.padEnd(30)}p50 ms`);
   for (const s of summary) {
      console.log(
         s.method.padEnd(20) +
            pct(s.precision).padEnd(14) +
            FORMS.map((f) => pct(s.by_form[f]).padEnd(10)).join("") +
            pct(s.exact_code_share).padEnd(11) +
            FORMS.map((f) => `${f} ${s.zero_relevant[f]}`).join(", ").padEnd(30) +
            s.p50_ms.toFixed(2),
      );
   }

   console.log(`\nper code, precision@10 of the exact form (code in message: share of its logs whose message contains the code):`);
   console.log(`${"code".padEnd(22)}${"causes".padEnd(8)}${"in msg".padEnd(8)}${methods.map((m) => m.slice(0, 9).padEnd(10)).join("")}`);
   for (const [i, q] of queries.entries()) {
      if (q.form !== "exact") continue;
      console.log(
         q.code.padEnd(22) + String(q.expected.length).padEnd(8) + pct(inMsg.get(q.code)!).padEnd(8) +
            methods.map((m) => pct(per[m][i].precision).padEnd(10)).join(""),
      );
   }

   // ---- the 60 typed queries: hybrid with and without the code list ----
   const textQueries: { text: string; expected: string; kind: string }[] =
      JSON.parse(readFileSync(path.join(ROOT, "evals/text_queries.json"), "utf8")).queries;
   const textMethods: Method[] = ["hybrid", ...codeMethods];
   const textPer: Record<string, number[]> = {};
   const changed: { text: string; codes: string[]; precision: Record<string, number> }[] = [];
   for (const q of textQueries) {
      const vec = toPgVector((await embed([q.text]))[0]);
      const row: Record<string, number> = {};
      for (const m of textMethods) {
         const hits = await searchOnce(q, vec, m);
         row[m] = hits.filter((h) => h.root_cause === q.expected).length / K;
         (textPer[m] ??= []).push(row[m]);
      }
      const codes = codesIn(q.text, knownCodes);
      if (codes.length) changed.push({ text: q.text, codes, precision: row });
   }
   console.log(`\n${textQueries.length} typed queries (evals/text_queries.json), precision@10:`);
   for (const m of textMethods) {
      console.log(`  ${m.padEnd(22)}${pct(mean(textPer[m]))}   nothing relevant: ${textPer[m].filter((x) => x === 0).length}`);
   }
   console.log(`  queries with a known code (${changed.length}):`);
   for (const c of changed) {
      console.log(`    ${c.text.padEnd(40)}[${c.codes.join(", ")}]  ${textMethods.map((m) => `${m.replace("hybrid + codes, ", "")} ${pct(c.precision[m])}`).join("  ")}`);
   }

   const out = flag("out") ? path.resolve(ROOT, flag("out")!) : path.join(ROOT, `evals/results/codes-${size}.json`);
   mkdirSync(path.dirname(out), { recursive: true });
   writeFileSync(
      out,
      JSON.stringify(
         {
            created_at: new Date().toISOString(),
            rows: info.rows,
            k: K,
            settings: { not_info: true, ef_search: SEARCH_DEFAULTS.efSearch, hybrid_candidates: SEARCH_DEFAULTS.hybridCandidates, rrf_k: SEARCH_DEFAULTS.rrfK },
            latency_note: "client-side wall time, median of 3 runs per query after a warm-up run",
            summary,
            text_queries: {
               summary: textMethods.map((m) => ({ method: m, precision: mean(textPer[m]), zero_relevant: textPer[m].filter((x) => x === 0).length })),
               with_codes: changed,
            },
            per_query: queries.map((q, i) => ({
               text: q.text, code: q.code, form: q.form, expected: q.expected,
               code_in_message: inMsg.get(q.code),
               methods: Object.fromEntries(methods.map((m) => [m, { precision: per[m][i].precision, same_code: per[m][i].exactCode, results: per[m][i].results }])),
            })),
         },
         null,
         2,
      ),
   );
   console.log(`\nwrote ${path.relative(ROOT, out)}`);
}

if (process.argv.includes("--generate")) {
   generate();
} else {
   run()
      .catch((err) => {
         console.error(err);
         process.exitCode = 1;
      })
      .finally(() => db.destroy());
}
